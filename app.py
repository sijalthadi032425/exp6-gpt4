from pathlib import Path
import traceback

from analysis_module import analyze_symptoms
from context_module import identify_missing_information
from flask import Flask, render_template, request, send_file
from prompt_module import create_medical_prompt
from question_module import generate_follow_up_questions
from safety_module import provide_medical_guidance
from save_module import save_analysis
from symptom_module import extract_symptoms

app = Flask(__name__)
OUTPUT_DIR = Path("outputs")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


@app.route("/", methods=["GET", "POST"])
def home():
    if request.method == "GET":
        return render_template(
            "index.html", report=None, patient_name="", error=None
        )

    # Collect patient details
    patient_name = request.form.get("patient_name", "").strip()
    age = request.form.get("age", "").strip()
    sex = request.form.get("sex", "").strip()
    symptoms = request.form.get("symptoms", "").strip()
    duration = request.form.get("duration", "").strip()
    severity = request.form.get("severity", "").strip()
    history = request.form.get("history", "").strip()
    medications = request.form.get("medications", "").strip()
    allergies = request.form.get("allergies", "").strip()

    # Validate required fields
    if not patient_name:
        return render_template(
            "index.html",
            report=None,
            patient_name="",
            error="Please enter the patient's name.",
        )

    if not age or not symptoms:
        return render_template(
            "index.html",
            report=None,
            patient_name=patient_name,
            error="Please enter the patient's age and symptoms.",
        )

    try:
        # Organize patient information
        patient_data = {
            "patient_name": patient_name,
            "age": age,
            "sex": sex or "Not provided",
            "symptoms": symptoms,
            "duration": duration or "Not provided",
            "severity": severity or "Not provided",
            "medical_history": history or "Not provided",
            "medications": medications or "Not provided",
            "allergies": allergies or "Not provided",
        }

        # Extract symptoms
        extracted_symptoms = extract_symptoms(symptoms)

        # Identify missing information
        missing_info = identify_missing_information(patient_data)

        # Create the patient profile
        profile = f"""
        Patient Name: {patient_data["patient_name"]}
        Age: {patient_data["age"]}
        Sex: {patient_data["sex"]}
        Medical History: {patient_data["medical_history"]}
        Current Medications: {patient_data["medications"]}
        Allergies: {patient_data["allergies"]}
        """

        # Create the prompt
        prompt = create_medical_prompt(
            patient_data, profile, extracted_symptoms, missing_info
        )

        # Send the prompt to Ollama for analysis
        analysis = analyze_symptoms(prompt)

        if not analysis or (
            isinstance(analysis, str)
            and analysis.startswith("Analysis could not be generated.")
        ):
            raise RuntimeError(
                "AI analysis failed. Check Ollama and the Llama 3.2 model."
            )

        # Generate follow-up questions
        follow_up_questions = generate_follow_up_questions(
            patient_data, missing_info
        )

        # Medical attention guidance
        medical_guidance = provide_medical_guidance()

        # Build the final report
        report = f"""
        MEDASSIST - AI SYMPTOM ASSISTANT
        ================================

        1. REPORTED SYMPTOMS
        {symptoms}

        2. PATIENT INFORMATION
        Patient Name: {patient_name}
        Age: {age}
        Sex: {sex or "Not provided"}
        Duration: {duration or "Not provided"}
        Severity: {severity or "Not provided"}
        Medical History: {history or "Not provided"}
        Current Medications: {medications or "Not provided"}
        Known Allergies: {allergies or "Not provided"}

        3. POSSIBLE CONDITIONS AND EXPLANATION
        {analysis}

        4. MISSING INFORMATION
        {missing_info}

        5. FOLLOW-UP QUESTIONS
        {follow_up_questions}

        6. MEDICAL ATTENTION GUIDANCE
        {medical_guidance}

        7. DISCLAIMER
        This report is generated by an AI system for educational and informational purposes only. It is not a medical diagnosis and must not replace professional medical advice, diagnosis, or treatment. Consult a qualified healthcare professional for medical concerns. Seek emergency care immediately for severe or life-threatening symptoms.
        ================================
        End of Report
        """

        # Save the report
        save_analysis(report)

        # Display the report
        return render_template(
            "index.html", report=report, patient_name=patient_name, error=None
        )

    except Exception as e:
        print("Error generating medical analysis:", e)
        traceback.print_exc()
        return render_template(
            "index.html",
            report=None,
            patient_name=patient_name,
            error=f"Analysis failed: {e}",
        )


@app.route("/download")
def download():
    report_path = OUTPUT_DIR / "medical_analysis.txt"
    if not report_path.exists():
        return "No report is available. Please analyze symptoms first.", 404

    return send_file(
        report_path,
        as_attachment=True,
        download_name="medical_analysis.txt",
        mimetype="text/plain",
    )


if __name__ == "__main__":
    app.run(debug=True)
